-- 공개 레이스 실시간 진행률 공유를 기본 켜짐으로 전환.
--
-- V70은 기본 꺼짐으로 나갔다. 근거는 "공개 레이스 상세는 모르는 사람도 조회할 수 있으니 동의를
-- 받고 시작한다"였는데, 실사용에서 대다수 사용자가 설정을 건드리지 않아 기능이 통째로 죽은 채로
-- 보인다는 문제가 먼저 드러났다(운동을 시작해도 아무 데이터가 생기지 않음). 개발자 판단으로
-- 기본값을 켜짐으로 바꾼다.
--
-- 기본값만 바꾸면 신규 행에만 적용되므로 기존 사용자는 계속 꺼진 상태로 남는다. 그래서 기존
-- 행도 함께 켠다 — 이미 가입한 사용자를 동의 없이 켜는 것이므로, 되돌리려면 내정보 설정에서
-- 각자 끌 수 있다는 점이 전제다.
--
-- 노출 범위 자체는 그대로다: 인증된 사용자에게만, 종료 전 레이스에서만, 크루 레이스는 크루
-- 내부자에게만 보인다. 좌표는 전송하지 않으며 15분간 갱신이 없으면 자동으로 사라진다.
alter table users
  alter column live_public_opt_in set default true;

update users
   set live_public_opt_in = true
 where live_public_opt_in = false;
