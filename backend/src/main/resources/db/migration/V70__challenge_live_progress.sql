-- 러닝 중 실시간(잠정) 진행률. 레이스 상세의 진행바가 완주 저장을 기다리지 않고 움직인다.
--
-- 확정 거리(total_km)와 완전히 분리한다. 잠정값은 표시 전용이며 완주·우승자·경품 판정에는
-- 절대 관여하지 않는다 — 조작되더라도 최악이 "잠깐 잘못 보였다"에서 멈추게 하기 위함이다.

alter table challenge_member
  -- 러닝 중 누적 거리. 확정 저장이 total_km에 반영되는 순간 비워진다(그대로 두면 이중합산).
  add column live_km numeric(10, 3),
  -- 마지막 갱신 시각. 15분 넘게 소식이 없으면 표시에서 무시한다 — 앱이 죽은 채 방치된 값이
  -- 영원히 "러닝 중"으로 남지 않게 하는 자동 청소.
  add column live_updated_at timestamptz,
  -- 일시정지 표시. 거리(live_km)는 유지하되 "러닝 중" 표시에서만 뺀다.
  -- 통째로 지우면 남들 화면에서 진행바가 확정값까지 내려앉았다 재개와 함께 다시 올라가
  -- 버그처럼 보인다. 다음 핑이 오면 자동으로 풀린다.
  add column live_paused boolean not null default false,
  -- 요청 순서 토큰(클라이언트가 요청을 만든 시각, ms). 핑·일시정지·삭제가 모두 이 값을 들고
  -- 오고 서버는 더 큰 값만 반영한다. 그래서 셋 사이의 순서가 네트워크 재정렬과 무관하게
  -- 고정된다 — 종료 시 보낸 일시정지가, 그보다 먼저 만들어졌지만 늦게 도착한 핑을 무효화한다.
  --
  -- 순서 보정 장치이지 인가 수단이 아니다. 요청자가 정하는 값이라 악의적 클라이언트는 언제든
  -- 큰 값을 보낼 수 있다 — 조작 방어는 목표 상한과 속도 검증이 담당한다.
  -- 서버가 값을 비우는 경로(확정 저장·실내런 승인·운동 삭제·탈퇴)는 이 토큰을 건드리지 않는다.
  -- 서버 시각으로 올리면 시계가 느린 기기의 다음 런이 스큐만큼 통째로 막힌다.
  add column live_sent_at bigint not null default 0;

-- 실시간 진행률을 남에게 보여줄지 — 공개 레이스와 크루 레이스를 각각 끌 수 있다.
-- 기본값이 서로 다른 것은 의도다: 공개 레이스는 모르는 사람도 조회할 수 있어 동의를 받고
-- 시작하고, 크루는 이미 서로 아는 폐쇄 로스터라 기본 허용하되 끌 수 있게 둔다.
-- 이 설정은 조회 시점에 확인한다(사건이 아니라 상태다) — 그래야 끄는 즉시 반영되고,
-- 끄기 직전에 발신된 핑이 뒤늦게 값을 되살려도 노출되지 않는다.
--
-- 테이블명이 users인 것에 주의: V48__rename_app_tables.sql에서 개칭돼 app_user는 없다.
alter table users
  add column live_public_opt_in boolean not null default false,
  add column live_crew_enabled boolean not null default true;
